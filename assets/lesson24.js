/* ================= ordering widget (E5, E6) ================= */
function orderWidget(poolId, seqId, items) {
  const pool = $(poolId), seq = $(seqId);
  const placed = [];
  const order = shuffle(items.map((_, i) => i));
  function render() {
    pool.innerHTML = ''; seq.innerHTML = '';
    order.filter(i => !placed.includes(i)).forEach(i => {
      const c = document.createElement('div');
      c.className = 'chip';
      c.innerHTML = bi(items[i].en, items[i].zh);
      c.addEventListener('click', () => { placed.push(i); render(); });
      pool.appendChild(c);
    });
    placed.forEach((i, k) => {
      const c = document.createElement('div');
      c.className = 'chip' + (items[i].mark ? ' ' + items[i].mark : '');
      c.innerHTML = `<span class="num">${k + 1}.</span>` + bi(items[i].en, items[i].zh);
      c.addEventListener('click', () => { placed.splice(k, 1); items.forEach(x => delete x.mark); render(); });
      seq.appendChild(c);
    });
  }
  render();
  return {
    placed: () => placed.slice(),
    setPlaced: arr => { placed.length = 0; arr.forEach(x => placed.push(x)); render(); },
    mark: fn => { placed.forEach((i, k) => { items[i].mark = fn(i, k); }); render(); },
  };
}

